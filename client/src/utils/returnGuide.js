/**
 * 만기 반납 전에 고객에게 보내는 안내와 직원 체크리스트(대표님 2026-11-10, 한일티엔에스 101호2197 반납 때).
 *
 * 근거는 장기렌트 약관이다: 제4조 ⑥⑦항(통행료·과태료, 반납 지연 대여료), 제6조(반납 상태),
 * 제14조(초과운행부담금), 제3조 ①항 6호(보증금 공제 후 반환).
 * 회사는 계약 종료일 뒤 1~2주 안의 반납을 정상으로 본다. 고객 안내에는 이 유예를 적지 않는다(반납이 늦어지는 것을 막으려고).
 */

import { korDate } from './endDocStyle.js';

const won = (n) => `${(Number(n) || 0).toLocaleString('ko-KR')}원`;
const km = (n) => `${(Number(n) || 0).toLocaleString('ko-KR')}km`;

/**
 * 고객 안내 사항 기본 문구. 한 줄이 한 항목이다.
 * @param {{ endDate?: string, annualKm?: number|string, origin?: '국산'|'외산', deposit?: number|string }} form
 * @returns {string[]}
 */
export const defaultReturnGuide = (form) => {
  const end = korDate(form.endDate) || '계약 종료일';
  const rate = form.origin === '외산' ? '1km당 200원' : '1km당 100원';
  const kmText = Number(form.annualKm) > 0 ? `약정 주행거리(연 ${km(form.annualKm)})` : '약정 주행거리';
  const deposit = Number(String(form.deposit ?? '').replace(/[^\d]/g, '')) || 0;
  return [
    `반납 일정: 계약 종료일(${end})에 맞춰 반납해 주시기 바랍니다. 일정 조정이 필요하시면 미리 담당자에게 연락 주세요. 협의 없이 반납이 늦어지면 계약에 따라 늦어진 기간의 대여료가 일할로 청구될 수 있습니다.`,
    '준비물: 차 키(보조키 포함)와 차량에 비치된 서류를 함께 반납해 주세요. 차량에 달린 블랙박스·내비게이션 등 부품은 떼지 말고 그대로 두시면 됩니다.',
    '개인 물품·정보 정리: 차 안의 개인 물품과 하이패스 카드를 챙겨 주시고, 필요한 블랙박스 영상은 미리 옮겨 두세요. 차량에 연결해 둔 휴대폰(블루투스)과 내비게이션 기록도 지워 주시기 바랍니다. 반납 후 남은 물품은 책임지기 어렵습니다.',
    '차량 점검: 반납하실 때 담당자와 함께 주행거리와 외관·실내 상태를 확인하고 사진으로 남깁니다. 정상적인 사용에 따른 마모 외의 손상은 계약에 따라 수리비(자차 면책 가입 시 사고 건당 고객부담금)가 청구됩니다.',
    `초과운행: ${kmText}를 넘은 경우 초과운행부담금을 정산합니다. ${rate}(VAT 별도)이며, 탁송·정비 운행을 감안해 2,000km를 빼고 계산합니다.`,
    '통행료·과태료: 반납일까지 운행하며 생긴 통행료, 과태료, 주차료 등은 고객님 부담입니다. 반납 뒤에 도착하는 고지서는 확인되는 대로 안내해 드립니다.',
    `렌트료 정산: 마지막 회차 렌트료는 평소와 같이 결제일에 출금됩니다. 초과운행·수리비 등 정산할 금액이 있으면 미리 안내해 드리고 함께 청구합니다.${deposit > 0 ? ` 보증금 ${won(deposit)}은 정산할 금액을 뺀 뒤 돌려드립니다.` : ''}`,
    '계약 종료: 정산이 모두 끝나면 계약종료 확인서를 보내 드립니다.'
  ];
};

/** 화면에서 고친 문구(form.guide)가 있으면 그것을, 없으면 기본 문구를 쓴다 */
export const returnGuideLines = (form) => (typeof form.guide === 'string'
  ? form.guide.split('\n').map((t) => t.trim()).filter(Boolean)
  : defaultReturnGuide(form));

/** 문자·카카오톡에 붙여 넣을 글 */
export const returnGuideText = (form) => {
  const facts = [
    `- 차량: ${[form.plateNo, form.carModel].filter(Boolean).join(' ') || '-'}`,
    `- 계약 종료일: ${korDate(form.endDate) || '-'}`,
    form.returnAt && `- 반납 일시: ${form.returnAt}`,
    form.place && `- 반납 장소: ${form.place}`,
    form.manager && `- 담당자: ${form.manager}`
  ].filter(Boolean);
  const body = returnGuideLines(form).map((t, i) => `${i + 1}. ${t}`);
  return [
    '[렌트베네핏] 차량 반납 안내', '',
    `${form.party || '고객'}님, 장기렌트 계약 만기에 따른 차량 반납을 안내해 드립니다.`, '',
    ...facts, '', ...body, '',
    '문의: 렌트베네핏 ☎ 02-547-0303', '감사합니다.'
  ].join('\n');
};

